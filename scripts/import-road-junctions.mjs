#!/usr/bin/env node
/**
 * Generates the seed migration of the road junctions & interchanges catalog (rides places,
 * docs/spec/05_giving_worlds.md §5.3, D71, {{D:junctions-catalog}}; gap G45).
 *
 * Source: Ministry of Transport "junction and interchange names" (data.gov.il package `zmt_names`,
 * CC BY), read through the official CKAN datastore API. Only existing places are kept
 * (status "existing" and "existing, to be upgraded"); planned ones are dropped.
 * Coordinates stay in Israel TM Grid (EPSG:2039) here; the migration converts them to
 * WGS84 with PostGIS, so no projection math lives in this script.
 *
 * The catalog is refreshed by re-running this script into a new migration — the app
 * never fetches the source at runtime.
 *
 * Usage: node scripts/import-road-junctions.mjs <out.sql>
 */
import { writeFileSync } from 'node:fs';

export const RESOURCE_ID = '09bbc3b7-7289-4beb-97c7-a10ebc4973c6';
const DATASTORE_URL = `https://data.gov.il/api/3/action/datastore_search?resource_id=${RESOURCE_ID}&limit=1000`;

// The source's Hebrew values, as Unicode escapes (Hebrew text lives only in locale files).
const EXISTING = '\u05E7\u05D9\u05D9\u05DD'; // "existing"
const JUNCTION = '\u05E6\u05D5\u05DE\u05EA'; // "junction"
const SPLIT = '\u05DE\u05E4\u05D5\u05E6\u05DC'; // "split"
const INTERCHANGE = '\u05DE\u05D7\u05DC\u05E3'; // "interchange"
const TO_BE_UPGRADED = '\u05DC\u05E9\u05D3\u05E8\u05D5\u05D2'; // "to be upgraded"

/** Source statuses kept: existing, and existing-to-be-upgraded (planned places are dropped). */
const EXISTING_STATUSES = new Set([EXISTING, `${EXISTING} ${TO_BE_UPGRADED}`]);

/** Source place types → catalog kind; a split junction is still a junction. */
const KIND_BY_TYPE = new Map([
  [JUNCTION, 'junction'],
  [`${JUNCTION} ${SPLIT}`, 'junction'],
  [INTERCHANGE, 'interchange'],
]);

const clean = (v) => (typeof v === 'string' && v.trim() ? v.trim() : null);

/** A number from the source, or NaN when absent — `Number(null)` would silently be 0. */
const num = (v) => (v == null || v === '' ? Number.NaN : Number(v));

/**
 * Maps one source record to a catalog row, or null when it is not an existing,
 * well-formed place (planned, unknown type, missing name or coordinates).
 */
export function toJunctionRow(record) {
  if (!EXISTING_STATUSES.has(clean(record.STATUS))) return null;
  const kind = KIND_BY_TYPE.get(clean(record.CURRENT));
  const nameHe = clean(record.HEBREW);
  const id = num(record.NUM);
  const x = num(record.X);
  const y = num(record.Y);
  if (!kind || !nameHe || !Number.isInteger(id) || !Number.isFinite(x) || !Number.isFinite(y)) return null;
  return {
    id,
    kind,
    nameHe,
    nameEn: clean(record.LATIN),
    nameAr: clean(record.ARABIC),
    roads: clean(record.RAODS), // sic — the source column is spelled RAODS
    x: Math.round(x * 100) / 100, // centimetre precision is far beyond what a pin needs
    y: Math.round(y * 100) / 100,
  };
}

/** SQL string literal (or null), with single quotes doubled. */
export function sqlText(v) {
  return v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`;
}

/** Renders the whole seed migration for the given catalog rows (sorted by id). */
export function renderSeedSql(rows, { fetchedOn }) {
  const values = [...rows]
    .sort((a, b) => a.id - b.id)
    .map((r) =>
      `  (${r.id}, ${sqlText(r.kind)}, ${sqlText(r.nameHe)}, ${sqlText(r.nameEn)}, ${sqlText(r.nameAr)}, ` +
      `${sqlText(r.roads)}, ${r.x}, ${r.y})`,
    )
    .join(',\n');
  return `-- 0513_seed_road_junctions | Road junctions & interchanges catalog (G45, D71).
-- GENERATED by scripts/import-road-junctions.mjs on ${fetchedOn} — do not edit by hand.
-- Source: Ministry of Transport "junction and interchange names", data.gov.il package zmt_names
-- (resource ${RESOURCE_ID}), license CC BY. Existing places only (${rows.length} rows).
-- Coordinates arrive in Israel TM Grid (EPSG:2039) and are converted to WGS84 by PostGIS.

begin;

insert into public.road_junctions (junction_id, kind, name_he, name_en, name_ar, roads, lat, lng)
select v.id, v.kind, v.name_he, v.name_en, v.name_ar, v.roads,
       extensions.ST_Y(p.geom), extensions.ST_X(p.geom)
  from (values
${values}
  ) as v(id, kind, name_he, name_en, name_ar, roads, x, y)
  cross join lateral (
    select extensions.ST_Transform(
             extensions.ST_SetSRID(extensions.ST_MakePoint(v.x, v.y), 2039), 4326) as geom
  ) p
on conflict (junction_id) do update
   set kind = excluded.kind, name_he = excluded.name_he, name_en = excluded.name_en,
       name_ar = excluded.name_ar, roads = excluded.roads, lat = excluded.lat, lng = excluded.lng;

commit;
`;
}

async function main(outPath) {
  if (!outPath) throw new Error('usage: node scripts/import-road-junctions.mjs <out.sql>');
  const res = await fetch(DATASTORE_URL);
  if (!res.ok) throw new Error(`datastore_search failed: HTTP ${res.status}`);
  const body = await res.json();
  const records = body?.result?.records ?? [];
  if (records.length === 0 || records.length < (body?.result?.total ?? 0)) {
    throw new Error(`incomplete page: got ${records.length} of ${body?.result?.total}`);
  }
  const rows = records.map(toJunctionRow).filter(Boolean);
  writeFileSync(outPath, renderSeedSql(rows, { fetchedOn: new Date().toISOString().slice(0, 10) }));
  console.log(`wrote ${rows.length} of ${records.length} places to ${outPath}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main(process.argv[2]).catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
